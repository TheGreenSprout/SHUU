        private static void AppendMap(StringBuilder sb, InputActionMap map, int indentLevel)
        {
            string indent = Indent(indentLevel);
            string innerIndent = Indent(indentLevel + 1);

            string mapId = SanitizeIdentifier(map.name) + "_Input";


            #region Map class
            sb.AppendLine($"{indent}#region {map.name} Map");

            sb.AppendLine($"{indent}public static class {mapId}");
            sb.AppendLine($"{indent}{{");

            #region Header
            sb.AppendLine($"{innerIndent}#region Header");

            sb.AppendLine($"{innerIndent}public const string mapName = \"{EscapeString(map.name)}\";");
            sb.AppendLine($"{innerIndent}public const ActionMapID mapID = ActionMapID.{SanitizeIdentifier(map.name)};");

            sb.AppendLine();
            sb.AppendLine();

            sb.AppendLine($"{innerIndent}public static bool IsEnabled(SHUU_PlayerInput player = null) => player != null ? player.IsMapEnabled(mapName) : SHUU_Input.IsMapEnabled(mapName);");

            sb.AppendLine();

            sb.AppendLine($"{innerIndent}public static void Enable(SHUU_PlayerInput player = null) {{");
            sb.AppendLine($"{innerIndent}    if (player != null) player.EnableMap(mapName);");
            sb.AppendLine($"{innerIndent}    else SHUU_Input.EnableMap(mapName);");
            sb.AppendLine($"{innerIndent}}}");
            sb.AppendLine($"{innerIndent}public static void Disable(SHUU_PlayerInput player = null) {{");
            sb.AppendLine($"{innerIndent}    if (player != null) player.DisableMap(mapName);");
            sb.AppendLine($"{innerIndent}    else SHUU_Input.DisableMap(mapName);");
            sb.AppendLine($"{innerIndent}}}");

            sb.AppendLine($"{innerIndent}#endregion");
            #endregion
            
            sb.AppendLine();
            sb.AppendLine();
            sb.AppendLine();

            #region Actions
            sb.AppendLine($"{innerIndent}#region Actions");

            sb.AppendLine();

            bool firstAction = true;
            foreach (var action in map.actions)
            {
                if (!firstAction)
                {
                    sb.AppendLine();
                    sb.AppendLine();
                }
                else firstAction = false;
                    
                AppendAction(sb, map, action, indentLevel + 1);
            }

            sb.AppendLine();

            sb.AppendLine($"{innerIndent}#endregion");
            #endregion

            sb.AppendLine($"{indent}}}");

            sb.AppendLine($"{indent}#endregion");
            #endregion
        }


