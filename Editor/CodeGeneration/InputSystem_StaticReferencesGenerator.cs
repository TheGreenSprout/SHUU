            sb.AppendLine($"{indent}public static class {outerClass}_ControlSchemeExtensions");
            sb.AppendLine($"{indent}{{");
            sb.AppendLine($"{innerIndent}public static string ToSchemeName(this {csType} scheme)");
            sb.AppendLine($"{innerIndent}{{");
            sb.AppendLine($"{innerIndent}    return scheme switch");
            sb.AppendLine($"{innerIndent}    {{");

            foreach (var scheme in asset.controlSchemes)
                sb.AppendLine($"{innerIndent}        {csType}.{SanitizeIdentifier(scheme.name)} => \"{EscapeString(scheme.name)}\",");

            sb.AppendLine($"{innerIndent}        _ => null");
            sb.AppendLine($"{innerIndent}    }};");
            sb.AppendLine($"{innerIndent}}}");
            sb.AppendLine($"{indent}}}");

            sb.AppendLine();

            sb.AppendLine($"{indent}public static class {outerClass}_ActionMapIDExtensions");
            sb.AppendLine($"{indent}{{");
            sb.AppendLine($"{innerIndent}public static string ToMapName(this {amType} map)");
            sb.AppendLine($"{innerIndent}{{");
            sb.AppendLine($"{innerIndent}    return map switch");
            sb.AppendLine($"{innerIndent}    {{");

