        private void GenerateForAsset(InputActionAsset asset)
        {
            if (asset == null || string.IsNullOrWhiteSpace(asset.name)) return;

            string fileName = SanitizeIdentifier(asset.name) + fileSuffix;
            string filePath = ResolveFilePath(DefaultFilePath, fileName);

            DataManager.EnsureDirectoryExists(filePath);

            File.WriteAllText(filePath, BuildFile(asset), new UTF8Encoding(false));

            AssetDatabase.ImportAsset(filePath);
            AssetDatabase.Refresh();
            Debug.Log($"Input System Static References generated for '{asset.name}':\n{filePath}");
        }


        private static string ResolveFilePath(string assetPath, string fileName)
        {
            foreach (var (_, path) in EnumerateAssetsWithPath<MonoScript>(fileName))
                if (string.Equals(Path.GetFileNameWithoutExtension(path), fileName, StringComparison.Ordinal)) return path;

            return Path.Combine(Path.GetDirectoryName(assetPath), fileName + ".cs");
        }
