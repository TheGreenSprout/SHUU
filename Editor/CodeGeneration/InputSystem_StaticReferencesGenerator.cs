        private static string BuildFile(InputActionAsset asset)
        {
            string className = SanitizeIdentifier(asset.name) + "_Input";

            var sb = new StringBuilder();


            sb.AppendLine("// <auto-generated>");
            sb.AppendLine("// This file was auto-generated by the SHUU Input System.");
            sb.AppendLine("// Do not edit manually — changes will be overwritten on next generation.");
            sb.AppendLine("// </auto-generated>");

            sb.AppendLine();
            sb.AppendLine();

            sb.AppendLine("using System;");
            sb.AppendLine("using System.Collections.Generic;");
            sb.AppendLine("using UnityEngine;");
            sb.AppendLine("using UnityEngine.InputSystem;");
            sb.AppendLine();
            sb.AppendLine("using SHUU.Utils.InputSystem;");

            sb.AppendLine();
            
            sb.AppendLine($"public static class {className}");
            sb.AppendLine("{");
            sb.Append(BuildCode(asset, 1));
            sb.AppendLine("}");

            sb.AppendLine();
            AppendExtensions(sb, asset, className, 0);

            return sb.ToString();
        }


        private static string BuildCode(InputActionAsset asset, int baseIndent = 0)
        {
            var sb = new StringBuilder();


            #region Header
            sb.AppendLine($"{Indent(baseIndent)}#region Header");
            sb.AppendLine();

            AppendControlSchemeEnum(sb, asset, baseIndent);

            sb.AppendLine();
            sb.AppendLine();

            AppendActionMapEnum(sb, asset, baseIndent);

            sb.AppendLine();
            sb.AppendLine();
            sb.AppendLine();

            AppendActionMapsHelper(sb, asset, baseIndent);

            sb.AppendLine();
            sb.AppendLine($"{Indent(baseIndent)}#endregion");
            #endregion


            #region Spacing
            sb.AppendLine();
            sb.AppendLine();
            sb.AppendLine();
            sb.AppendLine();
            sb.AppendLine();
            #endregion


            #region Body
            sb.AppendLine($"{Indent(baseIndent)}#region Body");
            sb.AppendLine();

            bool firstMap = true;
            foreach (var map in asset.actionMaps)
            {
                if (!firstMap)
                {
                    sb.AppendLine();
                    sb.AppendLine();
                    sb.AppendLine();
                    sb.AppendLine();
                }
                else firstMap = false;

                AppendMap(sb, map, baseIndent);
            }

            sb.AppendLine();
            sb.AppendLine($"{Indent(baseIndent)}#endregion");
            #endregion


            return sb.ToString();
        }
